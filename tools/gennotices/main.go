// Gennotices writes THIRD_PARTY_NOTICES.md: the license of every module linked into Volm, of the Go standard library, and of the Material Symbols icons that the settings window embeds.
//
// Run it from the repository root after changing dependencies:
//
//	go run ./tools/gennotices
package main

import (
	"bytes"
	"cmp"
	_ "embed"
	"encoding/json"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

const mainPackage = "./cmd/volm"

//go:embed material-symbols-LICENSE.txt
var materialSymbolsLicense string

type module struct {
	Path, Version, Dir string
	Main               bool
}

func main() {
	var out bytes.Buffer
	out.WriteString("# Third-party notices\n\n")
	out.WriteString("Volm includes the following software and assets. This file is generated by `go run ./tools/gennotices`; do not edit it by hand.\n\n")

	for _, m := range linkedModules() {
		section(&out, m.Path+" "+m.Version, licenseText(m.Dir))
	}
	section(&out, "Go standard library", licenseText(goEnv("GOROOT")))
	section(&out, "Material Symbols (Google, used in the settings window)", materialSymbolsLicense)

	if err := os.WriteFile("THIRD_PARTY_NOTICES.md", out.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote THIRD_PARTY_NOTICES.md (%d bytes)", out.Len())
}

// linkedModules lists the modules whose packages the app imports, directly or not, for Windows: the modules that end up in the executable.
func linkedModules() []module {
	cmd := exec.Command("go", "list", "-deps", "-json=Module", mainPackage)
	cmd.Env = append(os.Environ(), "GOOS=windows", "GOARCH=amd64")
	data, err := cmd.Output()
	if err != nil {
		log.Fatalf("go list: %v", err)
	}
	seen := map[string]module{}
	dec := json.NewDecoder(bytes.NewReader(data))
	for dec.More() {
		var pkg struct{ Module *module }
		if err := dec.Decode(&pkg); err != nil {
			log.Fatal(err)
		}
		if m := pkg.Module; m != nil && !m.Main {
			seen[m.Path] = *m
		}
	}
	mods := make([]module, 0, len(seen))
	for _, m := range seen {
		mods = append(mods, m)
	}
	slices.SortFunc(mods, func(a, b module) int { return cmp.Compare(a.Path, b.Path) })
	return mods
}

// goEnv asks the go command, which also builds the app, rather than the runtime of this tool.
func goEnv(name string) string {
	out, err := exec.Command("go", "env", name).Output()
	if err != nil {
		log.Fatalf("go env %s: %v", name, err)
	}
	return strings.TrimSpace(string(out))
}

func licenseText(dir string) string {
	for _, name := range []string{"LICENSE", "LICENSE.txt", "LICENSE.md", "COPYING"} {
		if data, err := os.ReadFile(filepath.Join(dir, name)); err == nil {
			return string(data)
		}
	}
	log.Fatalf("no license file in %s", dir)
	return ""
}

func section(out *bytes.Buffer, title, license string) {
	fmt.Fprintf(out, "## %s\n\n```text\n%s\n```\n\n", title, strings.TrimSpace(strings.ReplaceAll(license, "\r\n", "\n")))
}
